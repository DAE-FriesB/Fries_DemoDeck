namespace Ex.Core.Services;

/// <summary>Template files written by <see cref="RepoService.InitRepoAsync"/>.</summary>
public static class Templates
{
    public static string GitIgnore(ProjectType type) => type switch
    {
        ProjectType.Unity => UnityGitIgnore,
        _ => DotNetGitIgnore,
    };

    public static string GitAttributes(ProjectType type) => type switch
    {
        ProjectType.Unity => UnityGitAttributes,
        _ => DotNetGitAttributes,
    };

    public static string Readme(string name, ProjectType type) =>
        $"""
        # {name}

        Exercise repository ({(type == ProjectType.Unity ? "Unity project" : ".NET project")}).

        `main` only holds this README and the git settings. The exercises live on branches:

        ```
        weekNN/start      the start situation of a week
        weekNN/step-N     optional snapshots used in class
        weekNN/solution   the finished exercise
        ```

        Managed with the Exercises Pipeline client. Do not create bare `weekNN` branches.
        The `demo/` and `rescue/` namespaces are reserved for the client.

        """;

    private const string UnityGitIgnore =
        """
        # Unity generated
        /[Ll]ibrary/
        /[Tt]emp/
        /[Oo]bj/
        /[Bb]uild/
        /[Bb]uilds/
        /[Ll]ogs/
        /[Uu]ser[Ss]ettings/
        /[Mm]emoryCaptures/
        /[Rr]ecordings/

        # Asset meta data should only be ignored when the corresponding asset is also ignored
        !/[Aa]ssets/**/*.meta

        # IDE / project files generated by Unity
        .vs/
        .vscode/
        .idea/
        .gradle/
        ExportedObj/
        .consulo/
        *.csproj
        *.unityproj
        *.sln
        *.slnx
        *.suo
        *.tmp
        *.user
        *.userprefs
        *.pidb
        *.booproj
        *.svd
        *.pdb
        *.mdb
        *.opendb
        *.VC.db
        *.pidb.meta
        *.pdb.meta
        *.mdb.meta

        # Builds
        *.apk
        *.aab
        *.unitypackage
        *.app
        crashlytics-build.properties
        /[Aa]ssets/[Ss]treamingAssets/aa/*

        # OS
        .DS_Store
        Thumbs.db

        """;

    private const string DotNetGitIgnore =
        """
        # .NET build output
        [Bb]in/
        [Oo]bj/
        [Ll]og/
        [Ll]ogs/
        artifacts/
        TestResults/

        # IDE
        .vs/
        .vscode/
        .idea/
        *.user
        *.suo
        *.userprefs

        # OS
        .DS_Store
        Thumbs.db

        """;

    private const string UnityGitAttributes =
        """
        # Normalize line endings (no LFS, see the exercises plan).
        * text=auto

        *.cs     text diff=csharp
        *.shader text
        *.json   text
        *.md     text

        # Unity YAML assets: keep as text. Uncomment to use Unity's merge tool (UnityYAMLMerge).
        *.unity   text eol=lf
        *.prefab  text eol=lf
        *.asset   text eol=lf
        *.meta    text eol=lf
        *.mat     text eol=lf
        *.anim    text eol=lf
        *.controller text eol=lf
        # *.unity  merge=unityyamlmerge
        # *.prefab merge=unityyamlmerge

        # Binary
        *.png  binary
        *.jpg  binary
        *.jpeg binary
        *.psd  binary
        *.fbx  binary
        *.wav  binary
        *.mp3  binary
        *.ogg  binary
        *.ttf  binary
        *.otf  binary

        """;

    private const string DotNetGitAttributes =
        """
        # Normalize line endings.
        * text=auto

        *.cs     text diff=csharp
        *.csproj text
        *.sln    text eol=crlf
        *.json   text
        *.md     text

        *.png binary
        *.jpg binary
        *.ico binary

        """;
}
